/**
 * Generates flat key union types from locale JSON files.
 * Run: node scripts/generate-i18n-types.mjs
 * Output: src/i18n/generated-resources.d.ts
 *
 * This avoids TS2589 caused by i18next inferring deep nested types
 * from large JSON files (panels.json has 1174+ keys).
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs'
import { join, basename } from 'path'
import { fileURLToPath } from 'url'
import { dirname } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const LOCALES_DIR = join(__dirname, '..', 'public', 'locales', 'zh-CN')
const OUTPUT = join(__dirname, '..', 'src', 'i18n', 'generated-resources.d.ts')

/**
 * Recursively flatten a nested JSON object into dot-notation keys.
 * { a: { b: "x", c: "y" } } → ["a.b", "a.c"]
 */
function flattenKeys(obj, prefix = '') {
  const keys = []
  for (const [key, value] of Object.entries(obj)) {
    const fullKey = prefix ? `${prefix}.${key}` : key
    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      keys.push(...flattenKeys(value, fullKey))
    } else {
      keys.push(fullKey)
    }
  }
  return keys
}

function toPascalCase(str) {
  return str
    .split(/[-_]/)
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

const files = readdirSync(LOCALES_DIR).filter(f => f.endsWith('.json')).sort()
const lines = [
  '/**',
  ' * AUTO-GENERATED by scripts/generate-i18n-types.mjs',
  ' * Do not edit manually. Run: npm run i18n:types',
  ' */',
  '',
]

const nsTypeNames = []

for (const file of files) {
  const ns = basename(file, '.json')
  const typeName = `${toPascalCase(ns)}Keys`
  nsTypeNames.push({ ns, typeName })

  const json = JSON.parse(readFileSync(join(LOCALES_DIR, file), 'utf-8'))
  const keys = flattenKeys(json)

  lines.push(`export type ${typeName} =`)
  // Write keys in chunks to keep lines readable
  const chunks = []
  for (let i = 0; i < keys.length; i += 8) {
    chunks.push(keys.slice(i, i + 8).map(k => `  | '${k}'`).join('\n'))
  }
  lines.push(chunks.join('\n') + '\n')
  lines.push('')
}

// Generate a combined resources interface for i18next CustomTypeOptions
lines.push('/** Flat resource map for i18next CustomTypeOptions */')
lines.push('export interface FlatResources {')
for (const { ns, typeName } of nsTypeNames) {
  lines.push(`  ${ns}: Record<${typeName}, string>`)
}
lines.push('}')
lines.push('')

writeFileSync(OUTPUT, lines.join('\n'), 'utf-8')
console.log(`Generated ${OUTPUT}`)
console.log(`  ${files.length} namespaces, ${nsTypeNames.length} type unions`)
